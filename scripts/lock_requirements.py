"""Write requirements-release.txt: every package the release build installs, pinned by version AND hash.

    .venv\\Scripts\\python.exe scripts\\lock_requirements.py            # rewrite requirements-release.txt
    .venv\\Scripts\\python.exe scripts\\lock_requirements.py --check    # exit 1 if it is out of date with the venv

The release workflow installs that file with ``pip install --require-hashes``, so a wheel that was replaced on an
index after it was reviewed cannot reach an installer. Run this after changing requirements.txt or
requirements-dev.txt and installing them into the venv; commit the result with the change.

How: the packages are requirements-dev.txt plus everything they depend on, as installed in this venv (the
venv must match the requirement files). The hashes are those the indexes publish for the Windows / Python 3.12
wheels: PyPI's JSON API, and for llama-cpp-python (an extra index of GitHub release assets) the release asset's
SHA-256 from the GitHub API. Nothing is downloaded but that metadata.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import urllib.request
from importlib import metadata
from pathlib import Path

from packaging.requirements import Requirement
from packaging.tags import sys_tags
from packaging.utils import canonicalize_name, parse_wheel_filename

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "requirements-release.txt"
EXTRA_INDEX = "https://abetlen.github.io/llama-cpp-python/whl/cu124"
GITHUB_ASSETS = {"llama-cpp-python": "https://api.github.com/repos/abetlen/llama-cpp-python/releases/tags/v{v}-cu124"}
HEADER = f"""\
# GENERATED by scripts/lock_requirements.py from requirements-dev.txt and the venv: do not edit by hand.
# Every package of the release build, pinned by version and by the SHA-256 of its Windows / Python 3.12 wheel.
# The release workflow installs it with:  pip install --require-hashes --only-binary=:all: -r requirements-release.txt
--extra-index-url {EXTRA_INDEX}
"""


def _get(url: str) -> dict:
    req = urllib.request.Request(url, headers={"User-Agent": "voxflow-lock-requirements",
                                               "Accept": "application/json"})
    with urllib.request.urlopen(req, timeout=30) as resp:          # noqa: S310 - fixed https URLs
        return json.load(resp)


def roots(path: Path) -> list[str]:
    """Package names in a requirements file and the files it includes with ``-r``."""
    names: list[str] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if line.startswith("-r "):
            names += roots(path.parent / line[3:].strip())
        elif line and not line.startswith("-"):
            names.append(Requirement(line).name)
    return names


def closure(names: list[str]) -> dict[str, str]:
    """{canonical name: installed version} of ``names`` and all their (Windows, this Python) dependencies."""
    found: dict[str, str] = {}
    todo = list(names)
    while todo:
        name = canonicalize_name(todo.pop())
        if name in found:
            continue
        dist = metadata.distribution(name)
        found[name] = dist.version
        for spec in dist.requires or []:
            req = Requirement(spec)
            if req.marker is None or req.marker.evaluate({"extra": ""}):
                todo.append(req.name)
    return found


def wheel_hashes(name: str, version: str) -> list[str]:
    """SHA-256 of every wheel of ``name`` ``version`` that pip may pick on this machine."""
    ok = set(sys_tags())
    if name in GITHUB_ASSETS:
        assets = _get(GITHUB_ASSETS[name].format(v=version))["assets"]
        files = [(a["name"], a["digest"].split(":", 1)[1]) for a in assets if a.get("digest")]
    else:
        files = [(u["filename"], u["digests"]["sha256"]) for u in _get(f"https://pypi.org/pypi/{name}/{version}/json")["urls"]
                 if u["filename"].endswith(".whl")]
    out = sorted({digest for filename, digest in files if set(parse_wheel_filename(filename)[3]) & ok})
    if not out:
        raise SystemExit(f"no wheel of {name}=={version} for this platform")
    return out


def render() -> str:
    packages = closure(roots(ROOT / "requirements-dev.txt"))
    lines = [HEADER]
    for name in sorted(packages):
        hashes = " \\\n    ".join(f"--hash=sha256:{h}" for h in wheel_hashes(name, packages[name]))
        lines.append(f"{name}=={packages[name]} \\\n    {hashes}\n")
    return "".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="only compare with the file; exit 1 if it differs")
    args = ap.parse_args(argv)
    text = render()
    if args.check:
        same = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("requirements-release.txt is up to date" if same else "requirements-release.txt is out of date")
        return 0 if same else 1
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.name}: {text.count('==')} packages")
    return 0


if __name__ == "__main__":
    sys.exit(main())
